/**
 * Question / Intent Stop Words to strip from conversational queries
 */
const QUESTION_PATTERNS = [
  /^(?:ما\s+)?(?:هو\s+)?(?:حكم|فضل|اجر|جزاء|كيفية|صفة|طريقة|معنى|شرح|بيان)\s+/i,
  /^(?:ماذا|ما)\s+(?:نقول|يقال|اقول|يقال\s+لنا|افعل|يصنع|يقال\s+في)\s+(?:عند|في|قبل|بعد|اذا|اثناء)?\s*/i,
  /^(?:كيف|ماذا|هل|ما|اين|متى|من)\s+(?:هو|هي|كان|يقال|نقول|اقول|افعل|نفعل|يصلي|يتوضا|يغتسل|يجوز|يصح)?\s*/i,
  /^(?:اريد\s+)?(?:معرفة|البحث\s+عن|حديث\s+عن|احاديث\s+في|احاديث\s+عن|حديث\s+في|باب)\s+/i,
  /^(?:دعاء|اذكار|ذكر|رقية|علاج|ورد)\s+/i,
];

/**
 * Strips conversational question wrappers to uncover the exact Islamic Intent
 */
export function extractQueryCore(query: string): string {
  let cleaned = normalizeArabic(query).trim();
  for (const regex of QUESTION_PATTERNS) {
    cleaned = cleaned.replace(regex, '').trim();
  }
  return cleaned;
}

const GENERIC_FIQH_WORDS = new Set([
  'صلاة', 'صلاه', 'يوم', 'ماء', 'رجل', 'امراة', 'امرأة', 'بيت', 'اهل', 'كان', 'غير', 'احد', 'شيء', 'قوم', 'ناس', 'عمل',
  'امين', 'الامين', 'كاذب', 'الكاذب', 'صادق', 'الصادق', 'خائن', 'الخائن', 'نفس', 'النفس', 'يد', 'اليد', 'عين', 'العين'
]);

const semanticExpansionCache = new Map<string, string[]>();

/**
 * High-Intelligence Intent & Semantic Expansion Function with 0-allocation cache.
 * Returns core tokens, category keywords, and canonical Prophetic text markers.
 */
export function expandSemanticTerms(query: string): string[] {
  if (semanticExpansionCache.has(query)) {
    return semanticExpansionCache.get(query)!;
  }

  const normQuery = normalizeArabic(query).trim();
  if (!normQuery) return [];

  const coreQuery = extractQueryCore(query);
  const rawTokens = tokenizeArabic(query);
  const termsSet = new Set<string>();

  // 1. Add direct non-stop tokens
  for (const t of rawTokens) {
    if (t.length >= 2 && !INTENT_STOP_WORDS.has(t)) {
      termsSet.add(t);
    }
  }

  // 2. Scan all Intent & Topical Clusters
  for (const [category, data] of Object.entries(HADITH_INTENT_CLUSTERS)) {
    const normCat = normalizeArabic(category);

    const isMatched =
      normQuery.includes(normCat) ||
      coreQuery.includes(normCat) ||
      data.terms.some((t) => {
        const normT = normalizeArabic(t);
        return (
          normQuery.includes(normT) ||
          normT.includes(normQuery) ||
          (coreQuery.length >= 3 && normT.includes(coreQuery))
        );
      });

    if (isMatched) {
      if (!INTENT_STOP_WORDS.has(normCat) && !GENERIC_FIQH_WORDS.has(normCat)) {
        termsSet.add(normCat);
      }

      // Add cluster search terms
      for (const term of data.terms) {
        const normTerm = normalizeArabic(term);
        if (normTerm.includes(' ')) {
          termsSet.add(normTerm);
        }
        for (const tok of tokenizeArabic(normTerm)) {
          const stripped = tok.replace(/^ال/, '');
          if (
            tok.length >= 4 &&
            !INTENT_STOP_WORDS.has(tok) &&
            !INTENT_STOP_WORDS.has(stripped) &&
            !GENERIC_FIQH_WORDS.has(tok) &&
            !GENERIC_FIQH_WORDS.has(stripped)
          ) {
            termsSet.add(tok);
          }
        }
      }
    }
  }

  const result = Array.from(termsSet);
  if (semanticExpansionCache.size < 1000) {
    semanticExpansionCache.set(query, result);
  }
  return result;
}

export interface SemanticConceptResolution {
  topic: string;
  corePhrases: string[];
}

/**
 * Maps a natural search query or topic to its thematic concept and canonical prophetic phrases.
 */
export function resolveSemanticConcept(query: string): SemanticConceptResolution | null {
  const normQuery = normalizeArabic(query.trim());
  if (normQuery.length < 2) return null;

  for (const [topic, data] of Object.entries(HADITH_INTENT_CLUSTERS)) {
    const normTopic = normalizeArabic(topic);
    const matchesTopic = normQuery.includes(normTopic) || normTopic.includes(normQuery);
    const matchesTerm =
      !matchesTopic &&
      data.terms.some((t) => {
        const nt = normalizeArabic(t);
        return normQuery === nt || normQuery.includes(nt) || nt.includes(normQuery);
      });

    if (matchesTopic || matchesTerm) {
      const corePhrases = data.canonical
        .map(normalizeArabic)
        .filter((c) => c.length >= 10);

      return {
        topic,
        corePhrases,
      };
    }
  }

  return null;
}

