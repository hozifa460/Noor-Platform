/**
 * Retrieves morphological variants for a given word, checking compound prefixes,
 * single prefixes, and common spelling alternations (Taa Marbuta/Haa and Alef).
 */
export function getMorphologicalVariants(token: string): string[] {
  if (!token) return [];
  const candidates = new Set<string>();
  candidates.add(token);

  // Strip compound prefixes (e.g. وبال، فبال، كال، بال، فال، وال، لل، ال)
  const strippedCompound = token.replace(/^(?:وبال|فبال|كال|بال|فال|وال|لل|ال)/, '');
  if (strippedCompound && strippedCompound !== token) {
    candidates.add(strippedCompound);
  }

  // Strip single-letter prefixes (e.g. و، ف، ب، ك، ل)
  const strippedSingle = token.replace(/^[وفبكل]/, '');
  if (strippedSingle && strippedSingle !== token) {
    candidates.add(strippedSingle);
    const strippedBoth = strippedSingle.replace(/^ال/, '');
    if (strippedBoth && strippedBoth !== strippedSingle) {
      candidates.add(strippedBoth);
    }
  }

  // Handle common unvocalized spelling alternations (ة <-> ه, أ/إ/آ -> ا)
  const extra: string[] = [];
  for (const c of candidates) {
    if (c.endsWith('ة')) extra.push(c.slice(0, -1) + 'ه');
    if (c.endsWith('ه')) extra.push(c.slice(0, -1) + 'ة');
    if (/^[أإآ]/.test(c)) extra.push('ا' + c.slice(1));
  }
  for (const e of extra) candidates.add(e);

  const results = new Set<string>();
  for (const c of candidates) {
    const list = ISLAMIC_ROOT_VARIANTS[c];
    if (list) {
      for (const v of list) results.add(v);
    }
  }
  return Array.from(results);
}

